"""
score_ref_ab.py — the DECISIVE downstream verdict on the noise fix. For each reference condition
(noisy / denoised / hpf120 / zipenh) generated by cloud/ref_ab.py, measure the GENERATED OUTPUT:
  - NOISE:    mean spectral floor + band-shape over the takes (does the cleaner ref clean the output?)
  - IDENTITY: mean cosine to his centroid, with TWO independent encoders (ECAPA + Resemblyzer d-vector)
              — because clip-level identity != downstream, and one metric isn't proof.

Pull the pod's /workspace/ref_ab -> data/out/lecture1/ref_ab/ first, then:
  .venv/Scripts/python.exe scripts/score_ref_ab.py
Winner = the condition with the LOWEST output noise floor that holds identity >= noisy - 0.03 on BOTH
encoders. librosa & speechbrain conflict in one process, so each stage runs in its own subprocess.
"""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AB = ROOT / "data/out/lecture1/ref_ab"
ORDER = ["noisy", "denoised", "hpf120", "zipenh"]
TAG = "RESULT_JSON:"
try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass


def conds():
    return [c for c in ORDER if (AB / c).is_dir() and list((AB / c).glob("*.wav"))]


def _spectral():
    sys.path.insert(0, str(ROOT / "scripts"))
    from spectral_inspect import analyze, load
    import numpy as np
    out = {}
    for c in conds():
        A = [analyze(load(p)) for p in sorted((AB / c).glob("*.wav"))]
        floors = [a["floor"] for a in A]
        frac = {k: float(np.mean([a["frac"][k] for a in A])) for k in A[0]["frac"]}
        out[c] = dict(floor=float(np.mean(floors)), floor_sd=float(np.std(floors)), frac=frac, n=len(A))
    print(TAG + json.dumps(out))


def _identity(enc):
    sys.path.insert(0, str(ROOT / "scripts"))
    import numpy as np
    import verify_identity as vi
    embed = vi.build_ecapa() if enc == "ecapa" else vi.build_dvector()
    reals = vi.real_clip_names()
    cen = np.stack([embed(vi.CLIPS / n) for n in reals[:20]]).mean(0)
    cen /= (np.linalg.norm(cen) + 1e-9)
    dot = lambda p: float(np.dot(embed(p), cen))
    ceil = float(np.mean([dot(vi.CLIPS / n) for n in reals[20:40]]))
    out = {"_ceil": ceil}
    for c in conds():
        ids = [dot(p) for p in sorted((AB / c).glob("*.wav"))]
        out[c] = dict(id=float(np.mean(ids)), id_sd=float(np.std(ids)))
    print(TAG + json.dumps(out))


def _run(*mode):
    r = subprocess.run([sys.executable, __file__, *mode], capture_output=True, text=True)
    for line in r.stdout.splitlines():
        if line.startswith(TAG):
            return json.loads(line[len(TAG):])
    sys.exit(f"[{' '.join(mode)}] failed:\n{r.stdout[-600:]}\n{r.stderr[-1200:]}")


def main():
    cs = conds()
    if not cs:
        sys.exit(f"no takes in {AB} — pull the pod's /workspace/ref_ab there first")
    print(f"[spectral] output noise ({len(cs)} conds) ...")
    sp = _run("spectral")
    print("[ecapa] output identity ...")
    ec = _run("identity", "ecapa")
    print("[dvector] output identity (2nd encoder) ...")
    dv = _run("identity", "dvector")

    base = "noisy"
    print(f"\n{'condition':11s} {'out-floor':>10s} {'ΔdB vs noisy':>13s}   {'ECAPA id':>9s}  {'d-vec id':>9s}   verdict")
    print("-" * 82)
    rows = []
    for c in cs:
        dfloor = sp[c]["floor"] - sp[base]["floor"]
        de = ec[c]["id"] - ec[base]["id"]
        dd = dv[c]["id"] - dv[base]["id"]
        idsafe = (de >= -0.03) and (dd >= -0.03)
        v = "baseline" if c == base else ("✅ id-safe" if idsafe else "⚠ id-risk")
        rows.append(dict(c=c, floor=sp[c]["floor"], dfloor=dfloor, ecapa=ec[c]["id"], dvec=dv[c]["id"],
                         de=de, dd=dd, idsafe=(c == base or idsafe)))
        print(f"{c:11s} {sp[c]['floor']:10.1f} {dfloor:+13.1f}   {ec[c]['id']:9.3f}  {dv[c]['id']:9.3f}   {v}")
    print(f"\nECAPA ceiling {ec['_ceil']:.3f} · d-vector ceiling {dv['_ceil']:.3f} · identity bar = noisy − 0.03")

    # winner = identity-safe (both encoders), lowest output noise floor
    safe = [r for r in rows if r["idsafe"] and r["c"] != base]
    if safe:
        win = min(safe, key=lambda r: r["floor"])
        print(f"\nWINNER: '{win['c']}' — output noise {win['dfloor']:+.1f} dB vs noisy, "
              f"identity ΔECAPA {win['de']:+.3f} / Δd-vec {win['dd']:+.3f} (both within −0.03).")
    else:
        print("\nNo condition beats noise while staying identity-safe on BOTH encoders — "
              "keep noisy ref + rely on the funnel noise-gate, or accept a small identity cost.")
    print("(Two encoders must AGREE for a confident call — that's the double confirmation.)")


if __name__ == "__main__":
    a = sys.argv[1:]
    if a and a[0] == "spectral":
        _spectral()
    elif a and a[0] == "identity":
        _identity(a[1])
    else:
        main()
